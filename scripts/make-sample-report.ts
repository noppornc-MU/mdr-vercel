// Generates the SYNTHETIC sample microbiology report used by the demo:
//   fixtures/sample_report.svg (source) → fixtures/sample_report.png (via sharp)
// Fictional identifiers only (HN 0000123, Lab No 9900000001). No ward, no patient name.
// Run: npx tsx scripts/make-sample-report.ts
import { promises as fs } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

async function main() {
const expected = JSON.parse(
  await fs.readFile(path.join(process.cwd(), 'fixtures', 'sample_report.expected.json'), 'utf8'),
) as {
  lab_no: string; order_no: string; hn: string; sex: string; lab_received_raw: string;
  specimen_raw: string; isolates: { organism_raw: string; ast: { drug_raw: string; result: string }[] }[];
};

const W = 1000;
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const rows = expected.isolates[0].ast;
const rowH = 30;
const tableTop = 470;
const H = tableTop + 50 + rows.length * rowH + 170;
const mono = "font-family='Courier New, Courier, monospace'";
const sans = "font-family='Arial, Helvetica, sans-serif'";
const text = (x: number, y: number, s: string, extra = '') =>
  `<text x='${x}' y='${y}' ${sans} font-size='17' fill='#111' ${extra}>${esc(s)}</text>`;

const header = `
  <rect x='0' y='0' width='${W}' height='${H}' fill='#ffffff'/>
  <rect x='20' y='20' width='${W - 40}' height='${H - 40}' fill='none' stroke='#333' stroke-width='2'/>
  <text x='${W / 2}' y='62' ${sans} font-size='24' font-weight='bold' text-anchor='middle' fill='#0b3d6e'>DEMO HOSPITAL - DEPARTMENT OF MICROBIOLOGY</text>
  <text x='${W / 2}' y='92' ${sans} font-size='18' text-anchor='middle' fill='#333'>Culture and Antimicrobial Susceptibility Report</text>
  <rect x='40' y='108' width='${W - 80}' height='34' fill='#fde68a' stroke='#b45309'/>
  <text x='${W / 2}' y='131' ${sans} font-size='17' font-weight='bold' text-anchor='middle' fill='#7c2d12'>SYNTHETIC SAMPLE - NOT A REAL PATIENT - FOR DEMO ONLY</text>
  <line x1='40' y1='160' x2='${W - 40}' y2='160' stroke='#999'/>
  ${text(50, 192, 'Patient: [SYNTHETIC DEMO PATIENT]')}
  ${text(560, 192, `HN: ${expected.hn}`)}
  ${text(50, 224, `Sex: ${expected.sex === 'M' ? 'Male' : 'Female'}`)}
  ${text(560, 224, `Lab No: ${expected.lab_no}`)}
  ${text(50, 256, `Order No: ${expected.order_no}`)}
  ${text(560, 256, `Received: ${expected.lab_received_raw}`)}
  ${text(50, 288, `Specimen: ${expected.specimen_raw}`)}
  ${text(560, 288, 'Reported: 15/10/2569')}
  ${text(50, 320, 'Report status: Final')}
  <line x1='40' y1='340' x2='${W - 40}' y2='340' stroke='#999'/>
  ${text(50, 374, 'Culture result:', "font-weight='bold'")}
  ${text(50, 406, `Organism 1: ${expected.isolates[0].organism_raw}`, "font-style='italic'")}
  ${text(50, 438, 'Antimicrobial susceptibility (S = Susceptible, I = Intermediate, R = Resistant, D = SDD)')}
  <rect x='50' y='${tableTop}' width='560' height='36' fill='#e5e7eb' stroke='#555'/>
  <text x='64' y='${tableTop + 24}' ${sans} font-size='17' font-weight='bold'>Antimicrobial agent</text>
  <text x='520' y='${tableTop + 24}' ${sans} font-size='17' font-weight='bold'>Result</text>`;

const body = rows
  .map((r, i) => {
    const y = tableTop + 36 + i * rowH;
    return `<rect x='50' y='${y}' width='560' height='${rowH}' fill='${i % 2 ? '#f9fafb' : '#ffffff'}' stroke='#bbb'/>
  <text x='64' y='${y + 21}' ${mono} font-size='17'>${esc(r.drug_raw)}</text>
  <text x='540' y='${y + 21}' ${mono} font-size='18' font-weight='bold'>${esc(r.result)}</text>`;
  })
  .join('\n');

const footY = tableTop + 36 + rows.length * rowH + 40;
const footer = `
  ${text(50, footY, 'Comment: SYNTHETIC SAMPLE REPORT FOR DEMO - NOT A REAL PATIENT')}
  ${text(50, footY + 32, 'Reported by: Demo Lab (fictional)   Approved by: Demo Microbiologist (fictional)')}
  <text x='${W - 50}' y='${H - 36}' ${sans} font-size='14' text-anchor='end' fill='#666'>Generated by scripts/make-sample-report.ts</text>`;

const svg = `<?xml version='1.0' encoding='UTF-8'?>
<svg xmlns='http://www.w3.org/2000/svg' width='${W}' height='${H}' viewBox='0 0 ${W} ${H}'>
${header}
${body}
${footer}
</svg>
`;

const outDir = path.join(process.cwd(), 'fixtures');
await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(path.join(outDir, 'sample_report.svg'), svg, 'utf8');
await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(path.join(outDir, 'sample_report.png'));
console.log(`wrote fixtures/sample_report.svg and fixtures/sample_report.png (${W}x${H})`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
